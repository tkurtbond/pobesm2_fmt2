#!/usr/bin/env bash
# tools/perfcompare.sh -- compare two data files from tools/perfdata.sh
# and write a Markdown report to standard output (make perfcompare).
#
#   tools/perfcompare.sh BASE.tsv NEW.tsv [BASE_NAME NEW_NAME]
#
# BASE is what NEW is measured against: every ratio is NEW / BASE, so
# below 1 means NEW does less.  The names default to the files' labels.
#
# Stops (status 2) if the two files have different format versions or
# were measured on different inputs.  If the programs' outputs differ
# on any case, the report says so at the top: a comparison of programs
# that disagree means little.

set -euo pipefail

[ $# -ge 2 ] || { echo "usage: $0 BASE.tsv NEW.tsv [BASE_NAME NEW_NAME]" >&2; exit 2; }
base=$1 new=$2
for f in "$base" "$new"; do [ -r "$f" ] || { echo "perfcompare: can't read $f" >&2; exit 2; }; done

meta() { awk -F'\t' -v k="# $2" '$1 == k { print $2; exit }' "$1"; }
bname=${3:-$(meta "$base" label)}
nname=${4:-$(meta "$new" label)}

[ "$(meta "$base" version)" = "$(meta "$new" version)" ] \
  || { echo "perfcompare: data format versions differ ($(meta "$base" version), $(meta "$new" version)); rerun make perfdata in both repos" >&2; exit 2; }

awk -F'\t' -v bname="$bname" -v nname="$nname" -v bfile="$base" -v nfile="$new" '
function fmtm(x) { return (x == "NA") ? "NA" : sprintf("%.2f", x / 1e6) }
function fmtms(x) { return (x == "NA") ? "NA" : (x < 10 ? sprintf("%.2f", x) : sprintf("%.0f", x)) }
function ratio(a, b) { return (a == "NA" || b == "NA" || b == 0) ? "NA" : sprintf("%.2f", a / b) }
function range(med, lo, hi) { return fmtms(med) " (" fmtms(lo) "–" fmtms(hi) ")" }
function group(c) { sub(/-.*/, "", c); return c }
# Geometric mean accumulators, per group and overall.
function acc(g, key, r) { if (r == "NA") return; lsum[g, key] += log(r); lcnt[g, key]++ }
function gmean(g, key) { return lcnt[g, key] ? sprintf("%.2f", exp(lsum[g, key] / lcnt[g, key])) : "NA" }

FNR == 1 { which = (FILENAME == bfile) ? "b" : "n" }
/^# / { k = substr($1, 3); m[which, k] = $2; next }
$1 == "case" { next }
{
  key = $1 SUBSEP $2
  if (which == "b") { order[++nrows] = key; cases[$1] = 1 }
  for (i = 1; i <= NF; i++) d[which, key, i] = $i
  have[which, key] = 1
}
END {
  # Columns: 1 case, 2 format, 3 input_sha256, 4 input_bytes, 5 runs,
  # 6 output_sha256, 7-9 instr, 10-12 cpu_ms, 13-15 wall_ms, 16 maxrss_kb.
  for (r = 1; r <= nrows; r++) {
    key = order[r]
    if (!have["n", key]) { print "perfcompare: " nname " has no data for " key > "/dev/stderr"; exit 2 }
    if (d["b", key, 3] != d["n", key, 3]) {
      split(key, kk, SUBSEP)
      print "perfcompare: different inputs for " kk[1] "; rerun make perfdata in both repos with the same settings" > "/dev/stderr"; exit 2
    }
    if (d["b", key, 6] != d["n", key, 6]) { split(key, kk, SUBSEP); differ = differ " " kk[1] "/" kk[2] }
  }

  print "# Performance: " nname " vs " bname
  print ""
  print "Generated by `make perfcompare` in pobesm2_fmt2 (tools/perfcompare.sh),"
  print "from each repo'\''s `make perfdata` (tools/perfdata.sh). Every ratio is"
  print nname " / " bname ": below 1.00 means " nname " does less or is faster."
  print ""
  if (differ != "") {
    print "**WARNING: the two programs wrote different output for:" differ ".**"
    print "Their timings there compare different work."
    print ""
  } else {
    print "Both programs wrote identical output (standard output and error) for"
    print "every case and format."
    print ""
  }
  print "| | " bname " | " nname " |"
  print "|---|---|---|"
  split("commit date program program_sha256 cpu pinned_cpu perf copies", ks, " ")
  for (i = 1; i <= 8; i++) {
    v1 = m["b", ks[i]]; v2 = m["n", ks[i]]
    if (ks[i] == "program_sha256") { v1 = substr(v1, 1, 12); v2 = substr(v2, 1, 12) }
    print "| " ks[i] " | `" v1 "` | `" v2 "` |"
  }
  print ""
  print "## How to read this"
  print ""
  print "- **Instructions** (user-mode instructions retired, median of the runs)"
  print "  are the steadiest measure: they vary by about 0.03% between runs, so"
  print "  they compare two programs measured minutes apart. They leave out"
  print "  cache misses and the like, and time in the kernel."
  print "- **CPU ms** is the program'\''s own CPU time, user and system, median"
  print "  (minimum–maximum) over the runs, pinned to one CPU. It is what a user"
  print "  waits for, but it moves with clock speed and whatever else is running."
  print "- `small` runs one fixture as it is: mostly start-up and one"
  print "  entity. `doc` is the fixture'\''s entities repeated as one YAML"
  print "  document, `docs` as that many documents (see the copies row)."
  print "  `enyon-boase` is a real character; `synthetic` exercises every"
  print "  customizer shape, sorting, UTF-8 and wrapping."
  print ""

  for (r = 1; r <= nrows; r++) {
    key = order[r]; split(key, kk, SUBSEP); g = group(kk[1])
    ri = ratio(d["n", key, 7], d["b", key, 7]); rc = ratio(d["n", key, 10], d["b", key, 10])
    acc(g, "i", ri); acc("all", "i", ri); acc(g, "c", rc); acc("all", "c", rc)
    acc(kk[2], "i", ri); acc(kk[2], "c", rc)
  }
  print "## Summary"
  print ""
  print "Geometric means of the " nname " / " bname " ratios."
  print ""
  print "| Group | Instructions | CPU time |"
  print "|---|---|---|"
  split("small doc docs", gs, " ")
  for (i = 1; i <= 3; i++) print "| " gs[i] " inputs | " gmean(gs[i], "i") " | " gmean(gs[i], "c") " |"
  split("grid terse hmm rawms", fs, " ")
  for (i = 1; i <= 4; i++) print "| " fs[i] " format | " gmean(fs[i], "i") " | " gmean(fs[i], "c") " |"
  print "| **all** | **" gmean("all", "i") "** | **" gmean("all", "c") "** |"
  print ""

  print "## Details"
  last = ""
  for (r = 1; r <= nrows; r++) {
    key = order[r]; split(key, kk, SUBSEP)
    if (kk[1] != last) {
      last = kk[1]
      print ""
      print "### " kk[1] " (" d["b", key, 4] " bytes, " d["b", key, 5] " / " d["n", key, 5] " runs)"
      print ""
      print "| Format | Instr. " bname " (M) | Instr. " nname " (M) | Ratio | CPU ms " bname " | CPU ms " nname " | Ratio | Max RSS " bname " (KB) | Max RSS " nname " (KB) |"
      print "|---|---|---|---|---|---|---|---|---|"
    }
    print "| " kk[2] " | " fmtm(d["b", key, 7]) " | " fmtm(d["n", key, 7]) " | " ratio(d["n", key, 7], d["b", key, 7]) \
      " | " range(d["b", key, 10], d["b", key, 11], d["b", key, 12]) \
      " | " range(d["n", key, 10], d["n", key, 11], d["n", key, 12]) \
      " | " ratio(d["n", key, 10], d["b", key, 10]) \
      " | " d["b", key, 16] " | " d["n", key, 16] " |"
  }
}' "$base" "$new"
